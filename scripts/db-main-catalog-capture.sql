-- DB-CI-PG17: captura READ-ONLY del CATALOGO de MAIN (forma, SIN filas) para regenerar supabase/baseline/main_shape_subset.sql.
--
-- Un `set search_path` de sesion + UNA sentencia SELECT. Lee SOLO pg_catalog (definiciones de objetos de los esquemas public y private, y triggers propios
-- sobre auth.users). No lee ninguna fila de datos de usuarios ni de contenido, no ejecuta DDL/DML ni funciones con efectos,
-- no devuelve secretos. Se ejecuta en una transaccion de solo lectura (por ejemplo `begin transaction read only;` + esta
-- consulta + `rollback;`, o la herramienta `execute_sql` del MCP de Supabase) y devuelve una fila por seccion:
--   (seccion, sql) con las sentencias de la seccion separadas por salto de linea, en orden determinista.
-- Concatenando las secciones en orden (01..10) se obtiene `baseline_main.sql`, la entrada de
-- scripts/db-pg17-bootstrap-extract.mjs. El historial de migraciones se lee aparte (supabase_migrations.schema_migrations,
-- solo version y nombre) y se guarda en supabase/baseline/MAIN_MIGRATION_HISTORY.txt.
-- Mismo formato que la captura del 2026-09-29: CREATE TABLE en una linea, ALTER TABLE ... ADD CONSTRAINT, pg_get_indexdef,
-- pg_get_functiondef, pg_get_triggerdef, CREATE POLICY, REVOKE ALL + GRANT por destinatario, ALTER DEFAULT PRIVILEGES, COMMENT.
-- pg_get_* califican los nombres que NO estan en el search_path: con solo pg_catalog todo public.x / private.x sale calificado
-- (como en la captura del 2026-09-29). Es configuracion de la sesion, no escribe nada.
set search_path = pg_catalog;
with
ns as (
  select oid, nspname from pg_namespace where nspname in ('public', 'private')
),
ext_member as (
  select objid from pg_depend where deptype = 'e'
),
rel as (
  select c.oid, n.nspname, c.relname, c.relkind, c.relowner, c.relacl, c.relrowsecurity, c.relforcerowsecurity,
         n.nspname || '.' || c.relname as q
  from pg_class c join ns n on n.oid = c.relnamespace
  where c.relkind in ('r', 'p', 'v', 'm', 'S') and c.oid not in (select objid from ext_member)
),
fn as (
  select p.oid, n.nspname, p.proname, p.proowner, p.proacl, p.prokind,
         n.nspname || '.' || p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')' as sig
  from pg_proc p join ns n on n.oid = p.pronamespace
  where p.prokind in ('f', 'p') and p.oid not in (select objid from ext_member)
),
s01 as (
  select '01' as sec, 0 as o, 'SET check_function_bodies = false;' as k, 'SET check_function_bodies = false;' as stmt
  union all select '01', 1, 'a', 'SET search_path = public, extensions;'
  union all select '01', 2, n.nspname, 'CREATE SCHEMA IF NOT EXISTS ' || quote_ident(n.nspname) || ';' from ns n
  union all select '01', 3, e.extname,
    'CREATE EXTENSION IF NOT EXISTS ' || quote_ident(e.extname) || ' WITH SCHEMA ' || quote_ident(x.nspname) || ';'
  from pg_extension e join pg_namespace x on x.oid = e.extnamespace
  where e.extname not in ('plpgsql')
),
s02 as (
  select '02' as sec, 0 as o, r.q as k,
    'CREATE SEQUENCE IF NOT EXISTS ' || r.q || ' AS ' || format_type(s.seqtypid, null) || ' INCREMENT BY ' || s.seqincrement ||
    ' MINVALUE ' || s.seqmin || ' MAXVALUE ' || s.seqmax || ' START WITH ' || s.seqstart || ' CACHE ' || s.seqcache ||
    case when s.seqcycle then ' CYCLE;' else ' NO CYCLE;' end as stmt
  from rel r join pg_sequence s on s.seqrelid = r.oid
  where r.relkind = 'S'
    and not exists (select 1 from pg_depend d where d.objid = r.oid and d.deptype = 'i')
  union all
  select '02', 1, r.q,
    'CREATE TABLE ' || r.q || ' (' || string_agg(
      quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
      || case a.attidentity when 'a' then ' GENERATED ALWAYS AS IDENTITY' when 'd' then ' GENERATED BY DEFAULT AS IDENTITY' else '' end
      || case when a.attnotnull then ' NOT NULL' else '' end
      || case when a.attgenerated = 's' then ' GENERATED ALWAYS AS (' || pg_get_expr(d.adbin, d.adrelid) || ') STORED'
              when d.adbin is not null then ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid) else '' end,
      ', ' order by a.attnum) || ');'
  from rel r
  join pg_attribute a on a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
  where r.relkind in ('r', 'p')
  group by r.q
),
s03 as (
  select '03' as sec, case k.contype when 'p' then 0 when 'u' then 1 when 'x' then 2 else 3 end as o, r.q || ' ' || k.conname as k,
    'ALTER TABLE ' || r.q || ' ADD CONSTRAINT ' || quote_ident(k.conname) || ' ' || pg_get_constraintdef(k.oid) || ';' as stmt
  from pg_constraint k join rel r on r.oid = k.conrelid
  where k.contype in ('p', 'u', 'c', 'x')
),
s04 as (
  select '04' as sec, 0 as o, r.q || ' ' || k.conname as k,
    'ALTER TABLE ' || r.q || ' ADD CONSTRAINT ' || quote_ident(k.conname) || ' ' || pg_get_constraintdef(k.oid) || ';' as stmt
  from pg_constraint k join rel r on r.oid = k.conrelid
  where k.contype = 'f'
),
s05 as (
  select '05' as sec, 0 as o, r.q || ' ' || c.relname as k, pg_get_indexdef(i.indexrelid) || ';' as stmt
  from pg_index i join pg_class c on c.oid = i.indexrelid join rel r on r.oid = i.indrelid
  where not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid and k.contype in ('p', 'u', 'x'))
),
s06 as (
  select '06' as sec, 0 as o, f.sig as k, pg_get_functiondef(f.oid) || ';' as stmt
  from fn f
),
s07 as (
  select '07' as sec, 0 as o, t.tgrelid::regclass::text || ' ' || t.tgname as k, pg_get_triggerdef(t.oid) || ';' as stmt
  from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
  where not t.tgisinternal
    and (n.nspname in ('public', 'private') or (n.nspname = 'auth' and c.relname = 'users'))
    and t.oid not in (select objid from ext_member)
),
s08 as (
  select '08' as sec, 0 as o, r.q as k, 'ALTER TABLE ' || r.q || ' ENABLE ROW LEVEL SECURITY;' as stmt
  from rel r where r.relrowsecurity
  union all
  select '08', 1, r.q, 'ALTER TABLE ' || r.q || ' FORCE ROW LEVEL SECURITY;' from rel r where r.relforcerowsecurity
  union all
  select '08', 2, r.q || ' ' || p.polname,
    'CREATE POLICY ' || quote_ident(p.polname) || ' ON ' || r.q || ' AS ' || case when p.polpermissive then 'PERMISSIVE' else 'RESTRICTIVE' end ||
    ' FOR ' || case p.polcmd when 'r' then 'SELECT' when 'a' then 'INSERT' when 'w' then 'UPDATE' when 'd' then 'DELETE' else 'ALL' end ||
    ' TO ' || (select string_agg(case when x = 0 then 'public' else quote_ident(pg_get_userbyid(x)) end, ', ' order by case when x = 0 then '' else pg_get_userbyid(x) end)
               from unnest(p.polroles) x) ||
    coalesce(' USING (' || pg_get_expr(p.polqual, p.polrelid) || ')', '') ||
    coalesce(' WITH CHECK (' || pg_get_expr(p.polwithcheck, p.polrelid) || ')', '') || ';'
  from pg_policy p join rel r on r.oid = p.polrelid
),
-- Privilegios: por objeto, REVOKE ALL de los roles de la API y un GRANT por conjunto identico de privilegios (sin el dueno).
acl_obj as (
  select 'TABLE' as kind, r.q as name, r.relowner as owner, coalesce(r.relacl, acldefault((case when r.relkind = 'S' then 's' else 'r' end)::"char", r.relowner)) as acl,
         case when r.relkind = 'S' then 'SEQUENCE' else 'TABLE' end as word
  from rel r
  union all
  select 'FUNCTION', f.sig, f.proowner, coalesce(f.proacl, acldefault('f'::"char", f.proowner)),
         case f.prokind when 'p' then 'PROCEDURE' else 'FUNCTION' end
  from fn f
),
acl_rows as (
  select o.word, o.name, a.grantee, string_agg(a.privilege_type, ', ' order by a.privilege_type) as privs
  from acl_obj o cross join lateral aclexplode(o.acl) a
  where a.grantee <> o.owner
  group by o.word, o.name, a.grantee
),
acl_grouped as (
  select word, name, privs,
         string_agg(case when grantee = 0 then 'PUBLIC' else quote_ident(pg_get_userbyid(grantee)) end, ', '
                    order by case when grantee = 0 then '' else pg_get_userbyid(grantee) end) as grantees
  from acl_rows group by word, name, privs
),
col_acl as (
  select r.q, a.attname, x.grantee, x.privilege_type
  from rel r join pg_attribute a on a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped and a.attacl is not null
  cross join lateral aclexplode(a.attacl) x
  where x.grantee <> r.relowner
),
s09 as (
  select '09' as sec, 0 as o, o.word || ' ' || o.name as k,
    'REVOKE ALL ON ' || o.word || ' ' || o.name || ' FROM PUBLIC, anon, authenticated, service_role;' as stmt
  from acl_obj o
  union all
  select '09', 1, g.word || ' ' || g.name || ' ' || g.privs,
    'GRANT ' || g.privs || ' ON ' || g.word || ' ' || g.name || ' TO ' || g.grantees || ';'
  from acl_grouped g
  union all
  select '09', 2, c.q || ' ' || c.privilege_type || ' ' || pg_get_userbyid(c.grantee),
    'GRANT ' || c.privilege_type || ' (' || string_agg(quote_ident(c.attname), ', ' order by c.attname) || ') ON TABLE ' || c.q ||
    ' TO ' || case when c.grantee = 0 then 'PUBLIC' else quote_ident(pg_get_userbyid(c.grantee)) end || ';'
  from col_acl c group by c.q, c.privilege_type, c.grantee
  union all
  select '09', 3, pg_get_userbyid(d.defaclrole) || ' ' || coalesce(n.nspname, '') || ' ' || d.defaclobjtype::text || ' ' || pg_get_userbyid(x.grantee),
    'ALTER DEFAULT PRIVILEGES FOR ROLE ' || quote_ident(pg_get_userbyid(d.defaclrole)) || coalesce(' IN SCHEMA ' || quote_ident(n.nspname), '') ||
    ' GRANT ' || string_agg(x.privilege_type, ', ' order by x.privilege_type) || ' ON ' ||
    case d.defaclobjtype when 'r' then 'TABLES' when 'S' then 'SEQUENCES' when 'f' then 'FUNCTIONS' when 'T' then 'TYPES' when 'n' then 'SCHEMAS' end ||
    ' TO ' || case when x.grantee = 0 then 'PUBLIC' else quote_ident(pg_get_userbyid(x.grantee)) end || ';'
  from pg_default_acl d left join pg_namespace n on n.oid = d.defaclnamespace
  cross join lateral aclexplode(d.defaclacl) x
  where n.nspname is null or n.nspname in ('public', 'private')
  group by d.defaclrole, n.nspname, d.defaclobjtype, x.grantee
),
s10 as (
  select '10' as sec, 0 as o, r.q as k,
    'COMMENT ON ' || case when r.relkind = 'S' then 'SEQUENCE' when r.relkind in ('v', 'm') then 'VIEW' else 'TABLE' end || ' ' || r.q || ' IS ' || quote_literal(d.description) || ';' as stmt
  from rel r join pg_description d on d.objoid = r.oid and d.classoid = 'pg_class'::regclass and d.objsubid = 0
  union all
  select '10', 1, r.q || '.' || a.attname, 'COMMENT ON COLUMN ' || r.q || '.' || quote_ident(a.attname) || ' IS ' || quote_literal(d.description) || ';'
  from rel r join pg_attribute a on a.attrelid = r.oid and a.attnum > 0
  join pg_description d on d.objoid = r.oid and d.classoid = 'pg_class'::regclass and d.objsubid = a.attnum
  union all
  select '10', 2, r.q || ' ' || k.conname, 'COMMENT ON CONSTRAINT ' || quote_ident(k.conname) || ' ON ' || r.q || ' IS ' || quote_literal(d.description) || ';'
  from pg_constraint k join rel r on r.oid = k.conrelid
  join pg_description d on d.objoid = k.oid and d.classoid = 'pg_constraint'::regclass
  union all
  select '10', 3, f.sig, 'COMMENT ON ' || case f.prokind when 'p' then 'PROCEDURE' else 'FUNCTION' end || ' ' || f.sig || ' IS ' || quote_literal(d.description) || ';'
  from fn f join pg_description d on d.objoid = f.oid and d.classoid = 'pg_proc'::regclass
),
allstmts as (
  select * from s01 union all select * from s02 union all select * from s03 union all select * from s04 union all select * from s05
  union all select * from s06 union all select * from s07 union all select * from s08 union all select * from s09 union all select * from s10
)
select sec as seccion, count(*) as sentencias, string_agg(stmt, E'\n' order by o, k collate "C", stmt collate "C") as sql
from allstmts
group by sec
order by sec;
