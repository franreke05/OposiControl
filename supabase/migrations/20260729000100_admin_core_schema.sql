create or replace function private.touch_versioned_row()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at := now();
    new.version := old.version + 1;
    return new;
end;
$$;

create or replace function private.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at := now();
    return new;
end;
$$;

