-- Add uniqueness only when existing data is already clean. No rows are deleted.
do $$
begin
    if exists (
        select 1
        from public.user_role
        group by usuario_id, role_id
        having count(*) > 1
    ) then
        insert into private.migration_guardrail(code, details)
        values (
            'duplicate_user_role',
            '{"action":"deduplicate user_role before enforcing uniqueness"}'::jsonb
        )
        on conflict (code) do update
        set details = excluded.details, detected_at = now(), resolved_at = null;
    else
        create unique index if not exists idx_user_role_unique
            on public.user_role (usuario_id, role_id);
    end if;

    if exists (
        select 1
        from public.usuario
        where auth_user_id is not null
        group by auth_user_id
        having count(*) > 1
    ) then
        insert into private.migration_guardrail(code, details)
