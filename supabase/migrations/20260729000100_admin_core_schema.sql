        'articulo_tienda',
        'cartera_tickets',
        'inventario_usuario',
        'oferta_tienda',
        'recurso_temporal_tienda',
        'campana_rafaga',
        'support_conversation',
        'admin_preference'
    ]
    loop
        execute format(
            'drop trigger if exists oposicontrol_touch_version on public.%I',
            table_name
        );
        execute format(
            'create trigger oposicontrol_touch_version before update on public.%I ' ||
            'for each row execute function private.touch_versioned_row()',
            table_name
        );
    end loop;
end;
$$;

