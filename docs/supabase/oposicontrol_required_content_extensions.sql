create table if not exists public.opcion_pregunta (
  id int generated by default as identity primary key,
  pregunta_id int not null references public.pregunta(id) on delete cascade,
  etiqueta varchar not null,
  contenido text not null,
  es_correcta boolean not null default false,
  orden int not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);

create index if not exists idx_opcion_pregunta_pregunta_id
on public.opcion_pregunta (pregunta_id, orden);

create table if not exists public.noticia_layer (
  id uuid primary key default gen_random_uuid(),
  noticia_id int not null references public.noticia(id) on delete cascade,
  name varchar not null,
  kind varchar not null,
  content text not null default '',
  x int not null default 0,
  y int not null default 0,
  width int not null default 0,
  height int not null default 0,
  opacity int not null default 100,
  font_family varchar not null default 'sans',
  text_color varchar not null default '#FFFFFF',
  visible boolean not null default true,
  sort_order int not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);

create index if not exists idx_noticia_layer_noticia_id
on public.noticia_layer (noticia_id, sort_order);

create table if not exists public.oferta_tienda (
  id int generated by default as identity primary key,
  articulo_tienda_id int not null references public.articulo_tienda(id) on delete cascade,
  titulo varchar not null,
  discount_percent int,
  special_price_tickets int,
  starts_at timestamptz,
  ends_at timestamptz,
  status varchar not null default 'draft',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  constraint oferta_tienda_precio_o_descuento check (
    discount_percent is not null or special_price_tickets is not null
  )
);

create index if not exists idx_oferta_tienda_item
on public.oferta_tienda (articulo_tienda_id, starts_at, ends_at);

create table if not exists public.recurso_temporal_tienda (
  id int generated by default as identity primary key,
  articulo_tienda_id int not null references public.articulo_tienda(id) on delete cascade,
  recurso_id int not null references public.recurso_pregunta(id) on delete cascade,
  titulo varchar not null,
  starts_at timestamptz,
  ends_at timestamptz,
  access_duration_hours int not null default 24,
  status varchar not null default 'draft',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);

create index if not exists idx_recurso_temporal_tienda_item
on public.recurso_temporal_tienda (articulo_tienda_id, starts_at, ends_at);

create table if not exists public.campana_rafaga (
  id int generated by default as identity primary key,
  titulo varchar not null,
  descripcion text not null default '',
  tipo varchar not null,
  starts_at timestamptz,
  ends_at timestamptz,
  multiplier numeric not null default 1,
  reward_tickets int not null default 0,
  linked_exam_id int references public.examen(id) on delete set null,
  linked_store_item_id int references public.articulo_tienda(id) on delete set null,
  status varchar not null default 'draft',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);

create index if not exists idx_campana_rafaga_status_dates
on public.campana_rafaga (status, starts_at, ends_at);

