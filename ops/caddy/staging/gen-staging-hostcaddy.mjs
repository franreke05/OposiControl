// Generates ops/caddy/staging/Caddyfile.staging-hostcaddy from ops/caddy/Caddyfile.hostcaddy (itself generated from
// Caddyfile.production by scripts/gen-hostcaddy.mjs), so staging routes EXACTLY like production. Usage (repo root):
//   node ops/caddy/staging/gen-staging-hostcaddy.mjs            write the file
//   node ops/caddy/staging/gen-staging-hostcaddy.mjs --check    exit 1 if the committed file is stale (used by verify-ops-config.sh)
// The output is a SEPARATE site file that the production Caddyfile only `import`s: production site blocks are never edited.
// Changes against the production site: host names, loopback upstreams of the staging stack (18181 bot, 18183 control),
// Cloudflare Origin CA certificate from /etc/caddy/staging (no ACME: the records are proxied, the origin IP stays hidden),
// noindex header, and a second site (staging-control) that serves ONLY the control routes and health.
import fs from 'fs'

const SRC = 'ops/caddy/Caddyfile.hostcaddy'
const OUT = 'ops/caddy/staging/Caddyfile.staging-hostcaddy'
const API = 'staging-api.oposibots.es'
const CONTROL = 'staging-control.oposibots.es'
const BOT_UP = '127.0.0.1:18181'
const CONTROL_UP = '127.0.0.1:18183'
const TLS = '\ttls /etc/caddy/staging/origin.pem /etc/caddy/staging/origin.key'

const read = p => fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n')
const lines = read(SRC).split('\n').filter(l => !l.startsWith('#'))
const start = lines.findIndex(l => l === 'api.oposibots.es {')
if (start < 0) throw new Error('production site block not found in ' + SRC)
let prod = lines.slice(start).join('\n').trimEnd() + '\n'

const need = (s, what) => { if (!prod.includes(s)) throw new Error('not found in ' + SRC + ': ' + what); }
need('reverse_proxy 127.0.0.1:18083 {', 'control upstream')
need('reverse_proxy 127.0.0.1:18081 127.0.0.1:18082 {', 'bot pool upstream')
need('\tencode zstd gzip\n', 'encode line')

let api = prod
  .replace('api.oposibots.es {', API + ' {')
  .replace('\tencode zstd gzip\n', TLS + '\n\tencode zstd gzip\n')
  .replace('\t\t-Server\n', '\t\t-Server\n\t\tX-Robots-Tag "noindex, nofollow"\n')
  .replace(/127\.0\.0\.1:18083/g, CONTROL_UP)
  .replace(/127\.0\.0\.1:18081 127\.0\.0\.1:18082/g, BOT_UP)

// staging-control: same site without the bot pool; health goes to the control replica.
const botAt = api.indexOf('\t\t@bot path ')
const healthAt = api.indexOf('\t\t@health path ')
if (botAt < 0 || healthAt < botAt) throw new Error('bot/health blocks not where expected')
let control = (api.slice(0, botAt) + api.slice(healthAt))
  .replace(API + ' {', CONTROL + ' {')
  .replace(new RegExp(BOT_UP.replace(/\./g, '\\.'), 'g'), CONTROL_UP)

const leftovers = (api + control).match(/1808[123]|ktor-|^api\.oposibots\.es/gm)
if (leftovers) throw new Error('not adapted (production upstream or host left): ' + leftovers.join(','))
if (control.includes('@bot ') || control.includes(BOT_UP)) throw new Error('bot routes left in the control site')

const head = [
  '# STAGING sites for the host Caddy (system service) of oposibots-prod-01. GENERATED by ops/caddy/staging/gen-staging-hostcaddy.mjs',
  '# from ops/caddy/Caddyfile.hostcaddy: same routing as production (control matchers, bot pool, health on /health/live, deny by',
  '# default, /metrics and dev paths 404). Installed as /etc/caddy/staging/staging.caddy and pulled in by ONE line at the end of',
  '# the production Caddyfile: `import /etc/caddy/staging/staging.caddy`. Rollback = remove that line, validate, reload.',
  '# Upstreams: the loopback ports of ops/deploy/compose.staging.yaml only (never production\'s 18081-18083). TLS: Cloudflare',
  '# Origin CA certificate for both names (/etc/caddy/staging/origin.{pem,key}, readable by the caddy user). Do not hand-edit.',
  '',
].join('\n')
const text = head + api + '\n' + control

if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? read(OUT) : ''
  if (cur !== text) { console.error('STALE: ' + OUT + ' differs from the generator output; run node ' + 'ops/caddy/staging/gen-staging-hostcaddy.mjs'); process.exit(1) }
  console.log('up to date: ' + OUT)
} else {
  fs.writeFileSync(OUT, text)
  console.log('written ' + OUT + ' (' + text.split('\n').length + ' lines)')
}
